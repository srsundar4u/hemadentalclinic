CREATE TABLE charges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL REFERENCES appointments(id),
    description VARCHAR(500) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    charged_at TIMESTAMP NOT NULL,
    request_token VARCHAR(36) NOT NULL UNIQUE
);
CREATE INDEX charges_appointment_idx ON charges(appointment_id);
CREATE INDEX payments_appointment_idx ON payments(appointment_id);
ALTER TABLE payments ADD COLUMN request_token VARCHAR(36) UNIQUE;
